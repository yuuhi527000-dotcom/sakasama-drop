// =============================================
//  さかさまドロップ  設定ファイル
//  動き・時間は本家「ぷよぷよ通」の実測値（60コマ/秒）に合わせています
//  数字を変えるだけでゲームバランスを調整できます
// =============================================
window.SG = window.SG || {};

(function () {
  const F = 1000 / 60; // 1コマ（ミリ秒）

  SG.CONFIG = {
    FRAME: F,

    // 盤面（本家と同じ：横6×縦12、その上に見えない13段目。14段目は回転だけ使えて置くと消える）
    COLS: 6,
    ROWS: 13,
    HIDDEN: 1,
    SPAWN_X: 2,       // 出現する列（左から3列目）→ ここの12段目が埋まると負け
    COLORS: 4,        // 色の数

    // 落下（本家の対戦と同じ）
    FALL_INTERVAL: 32 * F,       // 1マス落ちる時間（32コマ＝本家ひとりモード最初の速さ。対戦の本家は16コマ）
    SOFT_DROP_INTERVAL: 2 * F,   // 下を押している間（2コマ／マス）
    GRACE: 32 * F,               // 着地してから動かせる合計時間（32コマ）。下を押していると即固定
    MAX_PUSHBACK: 8,             // 回転で押し上げられるのは8回まで
    BOUNCE: 16 * F,              // 置いたあとのぷにっと弾む時間（16コマ）
    ROTATE_ANIM: 7 * F,          // 回転の動き（7コマ）
    QUICKTURN_WINDOW: 20 * F,    // 両側がふさがった縦穴で、2回押しで上下入れ替え
    SPAWN_DELAY: 2 * F,          // 次のつぶが出てくるまで

    // 操作（左右の長押し：8コマ後から2コマごと）
    DAS: 8 * F,
    ARR: 2 * F,

    // 演出の時間
    POP_TIME: 50 * F,            // つぶが消える演出
    FLIP_ANIM: 480,              // さかさま演出（オリジナル）

    // ちぎれ・連鎖の落下（本家の物理：初速1ドット、加速0.1875、最高8ドット/コマ、1マス16ドット）
    FALL_V0: 1, FALL_ACC: 0.1875, FALL_VMAX: 8,
    // いしの落下（初速0、列ごとに加速が少しちがう）
    GARBAGE_ACC: [0.140625, 0.1484375, 0.125, 0.1640625, 0.1328125, 0.15625],

    // 対戦（本家と同じ）
    TARGET_POINT: 70,            // この点数ごとに相手へいし1個
    MARGIN_TIME: 96000,          // 96秒たつと、いしが送りやすくなり始める（マージンタイム）
    MARGIN_STEP: 16000,          // その後16秒ごとにさらに強くなる
    GARBAGE_MAX_DROP: 30,        // 1回に降るいしは最大30個（5段）
    ALL_CLEAR_BONUS: 30,         // 全消しボーナス（次の連鎖でいし30個分）

    // さかさまスキル（オリジナル）
    SKILL_GAUGE_MAX: 16,         // この数のつぶを消すとゲージ満タン（4個消し4回分）
    FLIP_CHAIN_ATTACKS: true     // 相手に反転されて起きた連鎖も攻撃になるか
  };
})();
